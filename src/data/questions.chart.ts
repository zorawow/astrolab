/**
 * 综合星盘解读 / 基础术语模块题目 + 引导式推理题。
 * 引导题要求逐步思考：先自己想，再逐层展开提示与示范，最后明确「不应推断的内容」。
 */

function guided(o: {
  id: string
  topic: string
  category: Question['category']
  unitId: string
  relatedIds: string[]
  prompt: string
  steps: GuidedStep[]
  notToInfer: string
  reviewIds: string[]
  conclusion: string
}): GuidedQuestion {
  return {
    id: o.id,
    type: 'guided',
    topic: o.topic,
    category: o.category,
    unitId: o.unitId,
    direction: 'application',
    relatedIds: o.relatedIds,
    prompt: o.prompt,
    steps: o.steps,
    notToInfer: o.notToInfer,
    explanation: o.conclusion,
    analysis: {
      whyCorrect: o.conclusion,
      reasoningChain: o.steps.map((s, i) => `第 ${i + 1} 步：${s.prompt} → ${s.answer}`),
      reviewIds: o.reviewIds,
      notToInfer: o.notToInfer,
    },
  }
}

